//! A local directory as the object store: one file per object.
//!
//! Writes go to a temporary file, are flushed to disk, and are renamed into
//! place, so a reader or a crash never observes a partial object. This is the
//! laptop and single-node backend; the protocol above it is unchanged.
use super::{Listed, ObjectStore, StoreError, StoreResult, dir_order};
use async_trait::async_trait;
use bytes::Bytes;
use std::{
    fs,
    io::{self, Read, Seek, SeekFrom, Write},
    path::{Path, PathBuf},
    sync::{
        Arc,
        atomic::{AtomicU64, Ordering},
    },
    time::{Duration, SystemTime},
};

pub struct FsStore {
    inner: Arc<Inner>,
}

struct Inner {
    root: PathBuf,
    tmp: PathBuf,
    /// Flush file contents and directory entries before acknowledging a write.
    sync: bool,
    /// Sets this store's temporary files apart from those of any other on
    /// the same directory, which may run under the same process id.
    nonce: u64,
    counter: AtomicU64,
}

fn unavailable(error: io::Error) -> StoreError {
    StoreError::Unavailable(error.to_string())
}

impl FsStore {
    pub fn open(root: impl Into<PathBuf>, sync: bool) -> StoreResult<Self> {
        let root = root.into();
        let tmp = root.join(".tmp");
        fs::create_dir_all(&tmp)
            .map_err(|e| StoreError::Fatal(format!("{}: {e}", root.display())))?;
        // Temporary files abandoned by a crash. Recent ones may belong to a
        // live process sharing this directory.
        if let Ok(entries) = fs::read_dir(&tmp) {
            let stale = SystemTime::now() - Duration::from_secs(600);
            for entry in entries.flatten() {
                if entry
                    .metadata()
                    .and_then(|m| m.modified())
                    .is_ok_and(|at| at < stale)
                {
                    let _ = fs::remove_file(entry.path());
                }
            }
        }
        Ok(Self {
            inner: Arc::new(Inner {
                root,
                tmp,
                sync,
                nonce: rand::random(),
                counter: AtomicU64::new(0),
            }),
        })
    }

    async fn run<T: Send + 'static>(
        &self,
        work: impl FnOnce(&Inner) -> io::Result<T> + Send + 'static,
    ) -> StoreResult<T> {
        let inner = self.inner.clone();
        tokio::task::spawn_blocking(move || work(&inner))
            .await
            .map_err(|e| StoreError::Unavailable(e.to_string()))?
            .map_err(unavailable)
    }
}

impl Inner {
    fn path(&self, key: &str) -> io::Result<PathBuf> {
        // Keys are generated by this program from validated names. Refuse
        // anything that could leave the root regardless.
        if key.is_empty()
            || key.starts_with('/')
            || key.split('/').any(|part| {
                part.is_empty() || part == "." || part == ".." || part.starts_with(".tmp")
            })
        {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "invalid object key",
            ));
        }
        Ok(self.root.join(key))
    }

    fn put(&self, key: &str, body: &[u8]) -> io::Result<()> {
        let path = self.path(key)?;
        let tmp = self.tmp.join(format!(
            "{}-{:016x}-{}",
            std::process::id(),
            self.nonce,
            self.counter.fetch_add(1, Ordering::Relaxed)
        ));
        let stored = self.place(&tmp, &path, body);
        if stored.is_err() {
            let _ = fs::remove_file(&tmp);
        }
        stored
    }

    fn place(&self, tmp: &Path, path: &Path, body: &[u8]) -> io::Result<()> {
        // Never through a file that already exists.
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(tmp)?;
        file.write_all(body)?;
        if self.sync {
            file.sync_data()?;
        }
        drop(file);
        let parent = path.parent().expect("keys have a parent");
        // The directories this write brings into being.
        let made: Vec<&Path> = parent
            .ancestors()
            .take_while(|dir| *dir != self.root && !dir.exists())
            .collect();
        // A concurrent delete may remove an emptied directory between the
        // create and the rename.
        let mut attempts = 0;
        loop {
            fs::create_dir_all(parent)?;
            match fs::rename(tmp, path) {
                Ok(()) => break,
                Err(e) if e.kind() == io::ErrorKind::NotFound && attempts < 8 => attempts += 1,
                Err(e) => return Err(e),
            }
        }
        if self.sync {
            // The new name, and the name of each directory made for it.
            fs::File::open(parent)?.sync_all()?;
            for dir in made {
                if let Some(above) = dir.parent() {
                    fs::File::open(above)?.sync_all()?;
                }
            }
        }
        Ok(())
    }

    fn delete(&self, key: &str) -> io::Result<()> {
        let path = self.path(key)?;
        match fs::remove_file(&path) {
            Ok(()) => {}
            Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(()),
            Err(e) => return Err(e),
        }
        // Drop directories this emptied; `remove_dir` refuses non-empty ones.
        let mut dir = path.parent();
        while let Some(parent) = dir {
            if parent == self.root || fs::remove_dir(parent).is_err() {
                break;
            }
            dir = parent.parent();
        }
        Ok(())
    }

    /// Keys below `prefix` in ascending order, stopping when `visit` says so.
    fn walk(&self, prefix: &str, visit: &mut dyn FnMut(String, u64) -> bool) -> io::Result<()> {
        let (dir, _) = prefix
            .rsplit_once('/')
            .map_or(("", prefix), |(d, n)| (d, n));
        let start = if dir.is_empty() {
            self.root.clone()
        } else {
            self.root.join(dir)
        };
        let base = if dir.is_empty() {
            String::new()
        } else {
            format!("{dir}/")
        };
        Self::walk_dir(&start, &base, prefix, visit).map(|_| ())
    }

    fn walk_dir(
        dir: &Path,
        base: &str,
        prefix: &str,
        visit: &mut dyn FnMut(String, u64) -> bool,
    ) -> io::Result<bool> {
        let entries = match fs::read_dir(dir) {
            Ok(entries) => entries,
            Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(true),
            Err(e) => return Err(e),
        };
        // Order names as the flat key space does: a directory sorts as `name/`.
        let mut names = Vec::new();
        for entry in entries {
            let entry = entry?;
            let Ok(name) = entry.file_name().into_string() else {
                continue;
            };
            if name.starts_with(".tmp") {
                continue;
            }
            let is_dir = entry.file_type()?.is_dir();
            names.push((
                if is_dir { format!("{name}/") } else { name },
                is_dir,
                entry,
            ));
        }
        names.sort_by(|a, b| a.0.cmp(&b.0));
        for (name, is_dir, entry) in names {
            let key = format!("{base}{name}");
            if is_dir {
                // Descend only where a matching key can exist.
                if !(key.starts_with(prefix) || prefix.starts_with(&key)) {
                    continue;
                }
                if !Self::walk_dir(&entry.path(), &key, prefix, visit)? {
                    return Ok(false);
                }
            } else if key.starts_with(prefix) {
                // The file may vanish between the listing and the stat.
                let Ok(meta) = entry.metadata() else { continue };
                if !visit(key, meta.len()) {
                    return Ok(false);
                }
            }
        }
        Ok(true)
    }
}

#[async_trait]
impl ObjectStore for FsStore {
    async fn put(&self, key: &str, body: Bytes) -> StoreResult<()> {
        let key = key.to_owned();
        self.run(move |inner| inner.put(&key, &body)).await
    }

    async fn get(&self, key: &str) -> StoreResult<Option<Bytes>> {
        let key = key.to_owned();
        self.run(move |inner| match fs::read(inner.path(&key)?) {
            Ok(body) => Ok(Some(Bytes::from(body))),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e),
        })
        .await
    }

    async fn get_range(&self, key: &str, start: u64, end: u64) -> StoreResult<Option<Bytes>> {
        let key = key.to_owned();
        self.run(move |inner| {
            let mut file = match fs::File::open(inner.path(&key)?) {
                Ok(file) => file,
                Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(None),
                Err(e) => return Err(e),
            };
            let len = file.metadata()?.len();
            let end = end.min(len);
            let start = start.min(end);
            file.seek(SeekFrom::Start(start))?;
            let mut body = vec![0; (end - start) as usize];
            file.read_exact(&mut body)?;
            Ok(Some(Bytes::from(body)))
        })
        .await
    }

    async fn exists(&self, key: &str) -> StoreResult<bool> {
        // One stat; cheaper inline than a hop to the blocking pool.
        let path = self.inner.path(key).map_err(unavailable)?;
        match fs::metadata(path) {
            Ok(_) => Ok(true),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(false),
            Err(e) => Err(unavailable(e)),
        }
    }

    async fn list(
        &self,
        prefix: &str,
        after: Option<&str>,
        limit: usize,
    ) -> StoreResult<Vec<Listed>> {
        let (prefix, after) = (prefix.to_owned(), after.map(str::to_owned));
        self.run(move |inner| {
            let mut out = Vec::new();
            inner.walk(&prefix, &mut |key, size| {
                if after.as_deref().is_none_or(|after| key.as_str() > after) {
                    out.push(Listed { key, size });
                }
                out.len() < limit
            })?;
            Ok(out)
        })
        .await
    }

    async fn list_dirs(
        &self,
        prefix: &str,
        after: Option<&str>,
        limit: usize,
    ) -> StoreResult<Vec<String>> {
        let (prefix, after) = (prefix.to_owned(), after.map(str::to_owned));
        self.run(move |inner| {
            let dir = inner.root.join(prefix.trim_end_matches('/'));
            let mut out = Vec::new();
            let entries = match fs::read_dir(dir) {
                Ok(entries) => entries,
                Err(e) if e.kind() == io::ErrorKind::NotFound => return Ok(out),
                Err(e) => return Err(e),
            };
            for entry in entries {
                let entry = entry?;
                if !entry.file_type()?.is_dir() {
                    continue;
                }
                if let Ok(name) = entry.file_name().into_string()
                    && !name.starts_with(".tmp")
                    && after
                        .as_deref()
                        .is_none_or(|after| dir_order(&name, after).is_gt())
                {
                    out.push(name);
                }
            }
            out.sort_by(|a, b| dir_order(a, b));
            out.truncate(limit);
            Ok(out)
        })
        .await
    }

    async fn delete(&self, key: &str) -> StoreResult<()> {
        let key = key.to_owned();
        self.run(move |inner| inner.delete(&key)).await
    }

    async fn purge(
        &self,
        prefix: &str,
        end: Option<&str>,
        doomed: &(dyn for<'a> Fn(&'a str) -> bool + Sync),
    ) -> StoreResult<usize> {
        let (owned_prefix, owned_end) = (prefix.to_owned(), end.map(str::to_owned));
        let keys = self
            .run(move |inner| {
                let mut keys = Vec::new();
                inner.walk(&owned_prefix, &mut |key, _| {
                    if owned_end.as_deref().is_some_and(|end| key.as_str() >= end) {
                        return false;
                    }
                    keys.push(key);
                    true
                })?;
                Ok(keys)
            })
            .await?;
        let keys: Vec<String> = keys.into_iter().filter(|key| doomed(key)).collect();
        let count = keys.len();
        self.run(move |inner| keys.iter().try_for_each(|key| inner.delete(key)))
            .await?;
        Ok(count)
    }
}
